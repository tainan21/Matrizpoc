import { mkdir, writeFile } from "node:fs/promises"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const outputDirectory = join(root, "assets", "sounds", "matriz-default")
const generatedModule = join(root, "src", "sounds", "assets.generated.ts")
const sampleRate = 16_000

const recipes = {
  "system.start": { frequencies: [220, 330, 440], durationMs: 300, gain: 0.24 },
  "system.end": { frequencies: [440, 330, 220], durationMs: 280, gain: 0.2 },
  notification: { frequencies: [660, 880], durationMs: 180, gain: 0.22 },
  message: { frequencies: [520, 700], durationMs: 160, gain: 0.18 },
  order: { frequencies: [392, 523, 659], durationMs: 260, gain: 0.24 },
  success: { frequencies: [523, 659, 784], durationMs: 240, gain: 0.22 },
  error: { frequencies: [220, 185], durationMs: 260, gain: 0.2 },
  warning: { frequencies: [330, 330, 440], durationMs: 250, gain: 0.18 },
  interaction: { frequencies: [760], durationMs: 90, gain: 0.12 },
  navigation: { frequencies: [410, 520], durationMs: 120, gain: 0.14 },
  open: { frequencies: [300, 450], durationMs: 140, gain: 0.14 },
  close: { frequencies: [450, 300], durationMs: 140, gain: 0.14 },
}

function fileNameFor(id) {
  return `${id.replaceAll(".", "-")}.wav`
}

function createWav({ frequencies, durationMs, gain }) {
  const sampleCount = Math.round((sampleRate * durationMs) / 1000)
  const dataSize = sampleCount * 2
  const buffer = Buffer.alloc(44 + dataSize)
  buffer.write("RIFF", 0)
  buffer.writeUInt32LE(36 + dataSize, 4)
  buffer.write("WAVE", 8)
  buffer.write("fmt ", 12)
  buffer.writeUInt32LE(16, 16)
  buffer.writeUInt16LE(1, 20)
  buffer.writeUInt16LE(1, 22)
  buffer.writeUInt32LE(sampleRate, 24)
  buffer.writeUInt32LE(sampleRate * 2, 28)
  buffer.writeUInt16LE(2, 32)
  buffer.writeUInt16LE(16, 34)
  buffer.write("data", 36)
  buffer.writeUInt32LE(dataSize, 40)

  for (let index = 0; index < sampleCount; index += 1) {
    const progress = index / sampleCount
    const segment = Math.min(frequencies.length - 1, Math.floor(progress * frequencies.length))
    const frequency = frequencies[segment]
    const attack = Math.min(1, progress / 0.08)
    const release = Math.min(1, (1 - progress) / 0.22)
    const envelope = attack * release
    const fundamental = Math.sin((2 * Math.PI * frequency * index) / sampleRate)
    const harmonic = Math.sin((2 * Math.PI * frequency * 2 * index) / sampleRate) * 0.16
    const sample = Math.max(-1, Math.min(1, (fundamental + harmonic) * gain * envelope))
    buffer.writeInt16LE(Math.round(sample * 32767), 44 + index * 2)
  }

  return buffer
}

await mkdir(outputDirectory, { recursive: true })
const generatedEntries = []

for (const [id, recipe] of Object.entries(recipes)) {
  const fileName = fileNameFor(id)
  const wav = createWav(recipe)
  await writeFile(join(outputDirectory, fileName), wav)
  generatedEntries.push(
    `  ${JSON.stringify(id)}: { source: ${JSON.stringify(`data:audio/wav;base64,${wav.toString("base64")}`)}, mimeType: "audio/wav", durationMs: ${recipe.durationMs} },`,
  )
}

const moduleSource = `/** Generated by scripts/generate-default-sounds.mjs. */\nexport const defaultSoundAssets = {\n${generatedEntries.join("\n")}\n} as const\n`
await writeFile(generatedModule, moduleSource, "utf8")
